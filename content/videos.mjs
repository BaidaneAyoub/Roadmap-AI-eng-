export function attachVideos(domains) {
  for (const domain of domains)
    for (const module of domain.modules)
      for (const lesson of module.lessons) {
        const keys = lessonVideoKeys[lesson.id];
        if (!keys) throw new Error(`Missing video curation: ${lesson.id}`);
        lesson.videos = [...new Set([...keys, fullCourses[domain.id]])].map(
          (k) => videos[k],
        );
        for (const concept of lesson.concepts) {
          const rule = conceptRules.find(([rx]) => rx.test(concept.name));
          const focused = concept.videoKeys
            ? videos[concept.videoKeys[0]]
            : rule
              ? videos[rule[1]]
              : videos[keys[0]];
          if (!focused)
            throw new Error(
              `Unknown video for concept: ${lesson.id}/${concept.name}`,
            );
          const companion = videos[fullCourses[domain.id]];
          concept.videos = [
            focused,
            ...(focused.url === companion.url ? [] : [companion]),
          ].map((v) => ({
            ...v,
            watchFor: `Focus on ${concept.name.toLowerCase()}. Then reproduce the lesson example: ${concept.example}`,
            scope:
              "Selected topic / relevant course section. Detailed implementation and adjacent topics also use the linked written resources.",
          }));
        }
      }
  return domains;
}
