function statVideo(pattern, fallback) {
  const link = stat.links.find((x) =>
    pattern.test(x.title.replace(/\s+/g, " ")),
  );
  if (!link) return fallback;
  const id = link.url.match(/(?:youtu\.be\/|v=)([\w-]{11})/)?.[1];
  if (!id) return fallback;
  return video(
    id,
    link.title.replace(/\s+/g, " ").replace(/�/g, "—"),
    "StatQuest · Josh Starmer",
    "Focused explanation",
    "A visual, step-by-step explanation of the topic named in the title.",
    "Use the worked intuition before writing the corresponding small experiment.",
    "https://statquest.org/video_index.html",
  );
}
